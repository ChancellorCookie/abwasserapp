qc.spike <- function(conc.org,conc.spk,conc.def){
  # Function o calculate the accuracy in spiked real samples
  #
  # For correct treatment:
  # The vector conc.org can be of length 1, or
  # the length of both vectors has to be the same.
  # For special pairing, conc.org and conc.spk must be named vectors to concatenate corresponding pairs
  
  # Check for length of vectors and select the case
  conc.org.Pair <- conc.org
  if (length(conc.org) > 1 && length(conc.org) != length(conc.spk)) {
    # Error handling
    if (length(conc.org) > length(conc.spk)) {
      return(list("conc.org" = conc.org.Pair,
                  "conc.spk" = conc.spk,
                  "Defined" = conc.def,
                  "Concentration" = NA,
                  "WFR" = NA))
    }
    # Pairing in loop
    conc.org.Pair <- c()
    for (i in 1:length(conc.spk)) {
      conc.org.Pair <-c(conc.org.Pair,
                        conc.org[str_detect(names(conc.spk)[i],paste0("^",names(conc.org)))]
                        )
    }
  }
  
  WFR <- (conc.spk - conc.org.Pair)/conc.def*100
  return(list("conc.org" = conc.org.Pair,
              "conc.spk" = conc.spk,
              "Defined" = conc.def,
              "Concentration" = (conc.spk - conc.org.Pair),
              "WFR" = WFR))
}

